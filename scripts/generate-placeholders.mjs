#!/usr/bin/env node

/**
 * Placeholder registry and the live-mode build gate.
 *
 * HANDOVER §3.3 asks for a generated swap checklist, and §3.4 for a build that
 * fails in live mode while any placeholder remains. Both live here.
 *
 *   SITE_MODE=showcase  (default)  writes content/PLACEHOLDERS.md and passes
 *   SITE_MODE=unlisted             same, but without the preview bar. Still
 *                                  noindex, so placeholders remain permitted.
 *   SITE_MODE=live                 writes it and FAILS if anything is tagged.
 *                                  This is the only indexable mode, which is
 *                                  why the gate lives here and nowhere else.
 *
 * §4.4 additionally asks for entries whose `reviewedOn` is over 12 months old
 * to be surfaced here, so the annual content pass is a list rather than a hunt.
 *
 * Run: node scripts/generate-placeholders.mjs
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "fs";
import { join, relative } from "path";

const ROOT = process.cwd();
const CONTENT = join(ROOT, "content");
const SITE_MODE = process.env.SITE_MODE || "showcase";
const STALE_AFTER_MONTHS = 12;

if (!["showcase", "unlisted", "live"].includes(SITE_MODE)) {
  console.error(
    `✗ SITE_MODE must be "showcase", "unlisted" or "live", got "${SITE_MODE}".`
  );
  process.exit(1);
}

const collections = existsSync(CONTENT)
  ? readdirSync(CONTENT, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort()
  : [];

const placeholders = [];
const stale = [];
const now = new Date();

function monthsSince(dateString) {
  const d = new Date(dateString);
  if (Number.isNaN(d.getTime())) return null;
  return (now.getFullYear() - d.getFullYear()) * 12 + (now.getMonth() - d.getMonth());
}

for (const collection of collections) {
  const dir = join(CONTENT, collection);
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()) {
    const path = join(dir, file);
    let entry;
    try {
      entry = JSON.parse(readFileSync(path, "utf-8"));
    } catch (err) {
      console.error(`✗ ${relative(ROOT, path)} is not valid JSON: ${err.message}`);
      process.exit(1);
    }
    const rel = relative(ROOT, path);
    if (entry.placeholder === true) {
      // With a whole entry tagged, every substantive field is suspect. List the
      // ones a human actually has to rewrite, rather than every key.
      const notable = [
        "overview",
        "description",
        "body",
        "quote",
        "eligibility",
        "whatWeDo",
        "entryRequirements",
        "certificateNotes",
        "denklikRoute",
        "summary",
        "tuitionBand",
        "coverageBand",
        "whoItSuits",
        "excerpt",
      ].filter((k) => k in entry);
      placeholders.push({
        collection,
        rel,
        fields: notable,
        slug: file.replace(/\.json$/, ""),
      });
    }
    if (entry.reviewedOn) {
      const age = monthsSince(entry.reviewedOn);
      if (age !== null && age >= STALE_AFTER_MONTHS) {
        stale.push({ rel, reviewedOn: entry.reviewedOn, age });
      }
    }
  }
}

// settings.json names its own unconfirmed scalars (§3.2).
const settingsPath = join(CONTENT, "settings.json");
let settingsPlaceholderFields = [];
if (existsSync(settingsPath)) {
  const settings = JSON.parse(readFileSync(settingsPath, "utf-8"));
  settingsPlaceholderFields = settings.placeholderFields || [];
}

// ── Write the registry ──────────────────────────────────────

const lines = [];
lines.push("# Placeholder registry");
lines.push("");
lines.push(
  "Generated by `scripts/generate-placeholders.mjs` on every build. Do not edit by hand."
);
lines.push("");
lines.push("This is the swap checklist. Every entry below is demo content that must be");
lines.push("replaced with something real before `SITE_MODE=live` will build.");
lines.push("");

if (placeholders.length === 0 && settingsPlaceholderFields.length === 0) {
  lines.push("**Empty. No placeholder content remains.**");
  lines.push("");
} else {
  lines.push(
    `**${placeholders.length} tagged entries**, plus ${settingsPlaceholderFields.length} unconfirmed settings values.`
  );
  lines.push("");
  const byCollection = {};
  for (const ph of placeholders) (byCollection[ph.collection] ||= []).push(ph);
  for (const collection of Object.keys(byCollection).sort()) {
    lines.push(`## ${collection}`);
    lines.push("");
    lines.push("| Entry | File | Fields to replace |");
    lines.push("|---|---|---|");
    for (const ph of byCollection[collection]) {
      lines.push(`| ${ph.slug} | \`${ph.rel}\` | ${ph.fields.join(", ") || "all"} |`);
    }
    lines.push("");
  }
  if (settingsPlaceholderFields.length > 0) {
    lines.push("## settings.json");
    lines.push("");
    lines.push("Scalar values still unconfirmed:");
    lines.push("");
    for (const f of settingsPlaceholderFields) lines.push(`- \`${f}\``);
    lines.push("");
  }
}

lines.push("## Images");
lines.push("");
lines.push(
  "See `content/image-credits.json`. That file doubles as the shot list for the"
);
lines.push(
  "real photo shoot, and every entry in it needs a recorded source and licence."
);
lines.push("");

if (stale.length > 0) {
  lines.push(`## Review overdue (${STALE_AFTER_MONTHS}+ months)`);
  lines.push("");
  lines.push("| File | Reviewed | Months ago |");
  lines.push("|---|---|---|");
  for (const s of stale) lines.push(`| \`${s.rel}\` | ${s.reviewedOn} | ${s.age} |`);
  lines.push("");
}

writeFileSync(join(CONTENT, "PLACEHOLDERS.md"), lines.join("\n"));

// ── Report and gate ─────────────────────────────────────────

const total = placeholders.length + settingsPlaceholderFields.length;
console.log(
  `📋 SITE_MODE=${SITE_MODE}. ${placeholders.length} placeholder entries, ${settingsPlaceholderFields.length} unconfirmed settings values.`
);
if (stale.length > 0) {
  console.warn(
    `⚠️  ${stale.length} entr${stale.length === 1 ? "y" : "ies"} overdue for review.`
  );
}
console.log("   Wrote content/PLACEHOLDERS.md");

if (SITE_MODE === "live" && total > 0) {
  console.error("");
  console.error(`❌ SITE_MODE=live but ${total} placeholder value(s) remain.`);
  console.error(
    "   See content/PLACEHOLDERS.md. Replace them, or build with SITE_MODE=showcase."
  );
  process.exit(1);
}
